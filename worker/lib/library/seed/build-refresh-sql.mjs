// Emits a migration that re-syncs seed fixtures into an existing DB without touching the founder's work:
// only rows still marked origin='fixture' AND edited=0 are updated.
// Usage: node --experimental-strip-types worker/lib/library/seed/build-refresh-sql.mjs migrations/03NN_library_seed_refresh.sql
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL(".", import.meta.url);
const read = (f) => JSON.parse(readFileSync(new URL(f, dir), "utf8"));
const out = process.argv[2];
if (!out) { console.error("usage: build-refresh-sql.mjs <migration file>"); process.exit(1); }
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- OWNER: library agent. GENERATED by worker/lib/library/seed/build-refresh-sql.mjs — re-syncs untouched seed fixtures.", ""];
let n = 0;
for (const lang of ["en", "ru"]) {
  for (const [id, m] of Object.entries(read(`materials.${lang}.json`))) {
    lines.push(`UPDATE lib_materials SET data = ${q(JSON.stringify(m))}, updated_at = unixepoch() WHERE resource_id = ${q(id)} AND lang = '${lang}' AND origin = 'fixture' AND edited = 0 AND data <> ${q(JSON.stringify(m))};`);
    n++;
  }
}
for (const c of read("collections.json")) {
  lines.push(`UPDATE lib_collections SET title_en = ${q(c.title_en)}, title_ru = ${q(c.title_ru)}, description_en = ${q(c.description_en)}, description_ru = ${q(c.description_ru)} WHERE id = ${q(c.id)};`);
}
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${n} material updates to ${out}`);
