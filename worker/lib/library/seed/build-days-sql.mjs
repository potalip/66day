// Emits a migration that moves seed resources to new curriculum days / retires outdated seeds — only where the row is
// still exactly as seeded (suggested_days equals the previous seed value), so founder edits always win.
// Usage: node worker/lib/library/seed/build-days-sql.mjs <old resources.json> <out.sql>
import { readFileSync, writeFileSync } from "node:fs";

const [oldFile, out] = process.argv.slice(2);
if (!oldFile || !out) { console.error("usage: build-days-sql.mjs <old resources.json> <out.sql>"); process.exit(1); }
const now = JSON.parse(readFileSync(new URL("resources.json", import.meta.url), "utf8"));
const prev = new Map(JSON.parse(readFileSync(oldFile, "utf8")).map((r) => [r.id, r]));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- OWNER: library agent. GENERATED by worker/lib/library/seed/build-days-sql.mjs — curriculum day mapping for seeds", ""];
for (const r of now) {
  const before = prev.get(r.id);
  if (!before) continue;
  const a = JSON.stringify(before.suggestedDays), b = JSON.stringify(r.suggestedDays);
  if (a !== b) lines.push(`UPDATE lib_resources SET suggested_days = ${q(b)}, updated_at = unixepoch() WHERE id = ${q(r.id)} AND created_by = 'seed' AND suggested_days = ${q(a)};`);
  if (r.retired && !before.retired) {
    lines.push(`UPDATE lib_resources SET status = 'review', featured = 0, admin_notes = COALESCE(admin_notes, 'Retired from the seed: outdated (curriculum review). Republish only if relabelled as historical.'), updated_at = unixepoch() WHERE id = ${q(r.id)} AND created_by = 'seed' AND status = 'published';`);
    lines.push(`INSERT INTO lib_events (resource_id, step, status, message) SELECT ${q(r.id)}, 'unpublish', 'info', 'retired from the seed (outdated)' WHERE EXISTS (SELECT 1 FROM lib_resources WHERE id = ${q(r.id)} AND created_by = 'seed');`);
  }
}
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${lines.length - 2} statements to ${out}`);
